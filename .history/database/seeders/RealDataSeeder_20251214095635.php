    /**
     * Generate a unique major code from major name
     * Uses first two letters of major name + timestamp suffix for uniqueness
     * Example: "الهندسة المدنية" -> "ه-1734" (first letter + last 4 digits of timestamp)
     * 
     * @param string $majorName
     * @return string
     */
    private function generateMajorCode(string $majorName): string
    {
        // Extract first letter (works with Arabic and English)
        $firstLetter = strtoupper(substr($majorName, 0, 1));
        
        // Use last 4 digits of Unix timestamp for uniqueness
        $suffix = substr((string) time(), -4);
        
        return "{$firstLetter}-{$suffix}";
    }
