                            ]
                        );
                        $majorIds[] = $major->id;
                    }

                    // Sync all majors to college (attach only new ones, keep existing)
                    if (!empty($majorIds)) {
                        $college->majors()->syncWithoutDetaching($majorIds);
                    }
                }
            }
